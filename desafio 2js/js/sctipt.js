function neon() {
document.getElementById("frasemotivadora").classList.remove("outline-text");
document.getElementById("frasemotivadora").classList.remove("retro-shadow");
document.getElementById("frasemotivadora").classList.add("neon-text");
}
function outline() {
document.getElementById("frasemotivadora").classList.remove("retro-shadow");
document.getElementById("frasemotivadora").classList.remove("neon-text");
document.getElementById("frasemotivadora").classList.add("outline-text");
}
function retro() {
document.getElementById("frasemotivadora").classList.remove("outline-text");
document.getElementById("frasemotivadora").classList.remove("neon-text");
document.getElementById("frasemotivadora").classList.add("retro-shadow");
}